import assert from 'node:assert/strict';
import {mkdtemp,rm,mkdir} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
const root=process.env.DSH_TARGET_CHECKOUT??path.resolve('.dsh-skill-build/targets/0.2.1-rc.3/checkout');
const from=p=>import(pathToFileURL(path.join(root,p)).href);
const {Context}=await from('vendor/cordis/lib/index.js');
const {default:LocalFs}=await from('packages/fs/fs-local/lib/index.js');
const {default:Storage}=await from('packages/storage/storage/lib/index.js');
const Json=await from('packages/storage/storage-json/lib/index.js');
const Domain=await from('packages/storage/storage-domain/lib/index.js');
const {default:WebRuntime}=await from('packages/web/web/lib/index.js');
const {createRequire}=await import('node:module');
const req=createRequire(path.join(root,'package.json'));const {z}=req('zod');
const temp=await mkdtemp(path.join(tmpdir(),'dsh-runtime-smoke-'));
const ctx=new Context();
try{
 await ctx.plugin(LocalFs,{cwd:temp});
 const target=await ctx.fs.resolve('test.txt');
 const first=await ctx.fs.writeText(target,'one',{kind:'createIfAbsent'});
 assert.equal(await ctx.fs.readText(target),'one');
 await ctx.fs.writeText(target,'two',{kind:'replaceIfVersion',version:first.version});
 await assert.rejects(ctx.fs.writeText(target,'bad',{kind:'replaceIfVersion',version:first.version}),e=>e.code==='FS_STALE_VERSION');
 const control=new AbortController();control.abort(new Error('local-cancel'));
 await assert.rejects(ctx.fs.readText(target,control.signal));
 await ctx.plugin(Storage);await ctx.plugin(Json,{root:path.join(temp,'records')});
 await ctx.plugin(Domain,{backend:'json'});
 const spec=Domain.defineDomain({name:'runtime_smoke',version:1,tables:{rows:Domain.domainTable(z.object({value:z.string()}))}});
 let d=await ctx.storageDomain.open(spec);await d.table('rows').put('a',{value:'persisted'});await d.close();
 d=await ctx.storageDomain.open(spec);assert.deepEqual(d.table('rows').get('a'),{value:'persisted'});await d.close();
 await assert.rejects(d.table('rows').put('b',{value:'closed'}),e=>e.code==='closed');
 await ctx.plugin(WebRuntime,{});
 const fiber=await ctx.plugin({name:'local-provider',inject:['web'],apply(inner){inner.web.registerSearchProvider({id:'local',available:()=>true,async search(request,signal){signal?.throwIfAborted();return {sources:[{url:'https://example.invalid/1'},{url:'https://example.invalid/2'}],truncated:false}}})}});
 const answer=await ctx.web.search({query:'local',maxResults:1});assert.equal(answer.sources.length,1);assert.equal(answer.truncated,true);
 await fiber.dispose();await assert.rejects(ctx.web.search({query:'local'}),e=>e.code==='WEB_PROVIDER_UNAVAILABLE');
 await ctx.fiber.dispose();assert.equal(ctx.get('fs'),undefined);assert.equal(ctx.get('storageDomain'),undefined);
 process.stdout.write(JSON.stringify({taskId:'runtime-contracts',checks:{'fs-guard':true,'cancel':true,'durable-reopen':true,'web-cap':true,'provider-unload':true,'service-unload':true}})+'\n');
}finally{await ctx.fiber.dispose();await rm(temp,{recursive:true,force:true});}
